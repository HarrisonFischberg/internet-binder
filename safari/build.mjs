// Builds the Safari copy of the extension: keepsake/ → safari/dist/.
// Safari does not run module service workers, so background.js and everything it imports
// become one classic script (same transform as the iOS core bundle). The manifest drops the
// Chrome-only keys. The Xcode project in safari/Keepsake references dist/, so run this first.
//
//   node safari/build.mjs

import { readFileSync, writeFileSync, rmSync, cpSync, existsSync } from 'node:fs';
import { dirname, join, basename, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { transform } from '../ios/tools/bundle-core.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, '..', 'keepsake');
const dist = join(here, 'dist');

const IMPORT_PATH = /^(?:import|export)\s*\{[^}]*\}\s*from\s*'(\.{1,2}\/[^']+\.js)';?\s*$/gm;

// Walk the background's import graph from its entry file.
function bundleBackground(entry) {
  const mods = {};
  const files = {};
  const visit = (file) => {
    const name = basename(file, '.js');
    if (files[name]) {
      if (files[name] !== file) throw new Error(`two modules named ${name}: ${files[name]}, ${file}`);
      return;
    }
    files[name] = file;
    const code = readFileSync(file, 'utf8');
    for (const [, rel] of code.matchAll(IMPORT_PATH)) visit(resolve(dirname(file), rel));
    mods[name] = transform(name, code);
  };
  visit(entry);
  const order = [];
  const seen = new Set();
  const place = (n, stack = []) => {
    if (seen.has(n)) return;
    if (stack.includes(n)) throw new Error(`import cycle: ${[...stack, n].join(' → ')}`);
    for (const d of mods[n].deps) place(d, [...stack, n]);
    seen.add(n);
    order.push(n);
  };
  Object.keys(mods).forEach((n) => place(n));
  return `// GENERATED by safari/build.mjs from keepsake/background.js. Do not edit.\n(function () {\nconst __m = {};\n${order.map((n) => mods[n].code).join('\n')}\n})();\n`;
}

if (existsSync(dist)) rmSync(dist, { recursive: true });
cpSync(src, dist, { recursive: true, filter: (p) => !/(^|\/)(\.DS_Store|README\.md)$/.test(p) });

writeFileSync(join(dist, 'background.js'), bundleBackground(join(src, 'background.js')));

const manifest = JSON.parse(readFileSync(join(src, 'manifest.json'), 'utf8'));
delete manifest.minimum_chrome_version;
delete manifest.background.type;
writeFileSync(join(dist, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');

console.log(`wrote ${dist}`);
