#!/usr/bin/env python3
"""Generate tokens.css (Chrome) and Theme.swift (Apple) from tokens/<style>.<mode>.json.

Styles: pantry (Pantry Pop, the default), notebook (Field Notebook), gallery, atlas (Night Atlas),
swiss (Swiss Index). Modes: light, dark. Role names are identical in every
file, so components never know which style is active. Standard library only.

    python3 -I replica/design/build_tokens.py

CSS contract: <html data-style="pantry|notebook|gallery|atlas|swiss" data-theme="light|dark"> where a
missing data-style means pantry and a missing data-theme means "follow the system".
"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
STYLES = ["pantry", "notebook", "gallery", "atlas", "swiss"]   # first = default
TITLES = {"pantry": "Pantry Pop", "notebook": "Field Notebook", "gallery": "Gallery", "atlas": "Night Atlas", "swiss": "Swiss Index"}
T = {(s, m): json.load(open(os.path.join(HERE, "tokens", f"{s}.{m}.json"))) for s in STYLES for m in ("light", "dark")}


def mode_vars(t):
    out = [f"--c-{k}: {v};" for k, v in t["color"].items()]
    out += [f"--shadow-{k}: {v};" for k, v in t["shadow"].items()]
    out.append(f"color-scheme: {t['mode']};")
    return out


def style_vars(t):
    d = t["display"]
    out = [f"--font-{k}: {v};" for k, v in t["font"].items()]
    out += [f"--w-display: {d['weight']};", f"--track-display: {d['tracking']};", f"--stretch-display: {d['stretch']};"]
    out.append(f"--bw: {t['stroke']}px;")
    out += [f"--r-{k}: {v}px;" for k, v in t["radius"].items()]
    return out


def block(sel, lines, indent="  "):
    return f"{sel} {{\n" + "\n".join(indent + l for l in lines) + "\n}"


def css():
    base = T[(STYLES[0], "light")]
    shared = []
    for k, t in base["type"].items():
        fam = "var(--font-display)" if t.get("font") == "display" else "var(--font-sans)"
        wt = "var(--w-display)" if t.get("font") == "display" else t["weight"]
        shared.append(f"--t-{k}: {wt} {t['size']}px/{t['line']}px {fam};")
    shared += [f"--s-{i}: {v}px;" for i, v in enumerate(base["space"])]
    shared += [f"--m-{k}: {base['motion'][k]};" for k in ("fast", "base", "slow", "ease")]
    out = ["/* Generated by build_tokens.py from tokens/*.json. Do not edit by hand. */"]
    for i, s in enumerate(STYLES):
        root = ":root" if i == 0 else f':root[data-style="{s}"]'
        light, dark = T[(s, "light")], T[(s, "dark")]
        lines = (shared if i == 0 else []) + style_vars(light) + mode_vars(light)
        out.append(block(root, lines))
        out.append("@media (prefers-color-scheme: dark) {\n" + block(f'  {root}:not([data-theme="light"])', mode_vars(dark), "    ") + "\n}")
        out.append(block(f'{root}[data-theme="dark"]', mode_vars(dark)))
    out.append("@media (prefers-reduced-motion: reduce) { :root { --m-fast: 0ms; --m-base: 0ms; --m-slow: 0ms; } }")
    return "\n".join(out) + "\n"


def swift_name(k):
    p = k.split("-")
    return p[0] + "".join(x.title() for x in p[1:])


def rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))


def swift():
    keys = list(T[(STYLES[0], "light")]["color"].keys())
    o = ["// Generated by build_tokens.py from tokens/*.json. Do not edit by hand.",
         "// PROPOSAL: not part of any Xcode target yet.",
         "import SwiftUI", "",
         "enum KSStyle: String, CaseIterable, Identifiable {",
         "    case " + ", ".join(STYLES),
         "    var id: String { rawValue }",
         "    var title: String { switch self { " + "; ".join(f'case .{x}: \"{TITLES[x]}\"' for x in STYLES) + " } }",
         "}", "",
         "private func dyn(_ l: (Double, Double, Double), _ d: (Double, Double, Double)) -> Color {",
         "    #if os(macOS)",
         "    Color(nsColor: NSColor(name: nil) { $0.bestMatch(from: [.darkAqua, .vibrantDark]) != nil",
         "        ? NSColor(srgbRed: d.0, green: d.1, blue: d.2, alpha: 1)",
         "        : NSColor(srgbRed: l.0, green: l.1, blue: l.2, alpha: 1) })",
         "    #else",
         "    Color(uiColor: UIColor { $0.userInterfaceStyle == .dark",
         "        ? UIColor(red: d.0, green: d.1, blue: d.2, alpha: 1)",
         "        : UIColor(red: l.0, green: l.1, blue: l.2, alpha: 1) })",
         "    #endif", "}", "",
         "/// Every colour role, resolved for light and dark. Pick one with `KSPalette.for(style)`.",
         "struct KSPalette {"]
    o += [f"    let {swift_name(k)}: Color" for k in keys]
    o += ["", "    static func `for`(_ style: KSStyle) -> KSPalette {", "        switch style {"]
    for s in STYLES:
        l, d = T[(s, "light")]["color"], T[(s, "dark")]["color"]
        args = []
        for k in keys:
            a, b = rgb(l[k]), rgb(d[k])
            args.append(f"            {swift_name(k)}: dyn(({a[0]:.4f}, {a[1]:.4f}, {a[2]:.4f}), ({b[0]:.4f}, {b[1]:.4f}, {b[2]:.4f}))")
        o.append(f"        case .{s}: return KSPalette(\n" + ",\n".join(args) + ")")
    o += ["        }", "    }", "}", "",
          "struct KSShape {", "    let sm: CGFloat, md: CGFloat, lg: CGFloat, xl: CGFloat",
          "    static func `for`(_ style: KSStyle) -> KSShape {", "        switch style {"]
    for s in STYLES:
        r = T[(s, "light")]["radius"]
        o.append(f"        case .{s}: return KSShape(sm: {r['sm']}, md: {r['md']}, lg: {r['lg']}, xl: {r['xl']})")
    o += ["        }", "    }", "}", "",
          "/// Headings per style (see each token file's display.ios).",
          "enum KSFont {",
          "    static func heading(_ style: KSStyle, _ text: Font.TextStyle) -> Font {",
          "        switch style {",
          "        case .pantry: return .custom(\"BricolageGrotesque-ExtraBold\", size: 28, relativeTo: text)",
          "        case .notebook: return .system(text, design: .serif).weight(.semibold)",
          "        case .gallery: return .system(text, design: .serif)",
          "        case .atlas: return .system(text).weight(.semibold)",
          "        case .swiss: return .system(text).weight(.heavy).width(.condensed)",
          "        }", "    }",
          "    static let body = Font.body", "    static let subhead = Font.subheadline.weight(.medium)",
          "    static let footnote = Font.footnote", "    static let caption = Font.caption.weight(.medium)",
          "}", "",
          "enum KSSpace {"]
    o += [f"    static let s{i}: CGFloat = {v}" for i, v in enumerate(T[(STYLES[0], "light")]["space"])]
    o += ["}"]
    return "\n".join(o) + "\n"


import re

def shadow_css(text):
    """The same tokens for a closed shadow root: :root[...] becomes :host([...])."""
    def host(m):
        chain = m.group(1)
        return f":host({chain})" if chain else ":host"
    return re.sub(r":root((?:\[[^\]]+\]|:not\(\[[^\]]+\]\))*)", host, text)

EXT = os.path.join(HERE, "..", "..", "keepsake", "src")
css_text = css()
open(os.path.join(HERE, "tokens.css"), "w").write(css_text)
open(os.path.join(HERE, "Theme.swift"), "w").write(swift())
# The extension's copies. tests/check-extension.test.mjs fails if these drift from the token sources.
open(os.path.join(EXT, "shared", "tokens.css"), "w").write(css_text)
open(os.path.join(EXT, "content", "tokens-content.js"), "w").write(
    "// Generated by replica/design/build_tokens.py. Do not edit by hand.\n"
    "// Keepsake design tokens for the in-page capture card (a closed shadow root): the host element\n"
    "// carries data-style and data-theme, exactly like <html> in the extension's own pages.\n"
    "globalThis.__keepsakeTokenCss = " + json.dumps(shadow_css(css_text)) + ";\n")
print("wrote tokens.css, Theme.swift and the extension copies for", ", ".join(STYLES))
