#!/usr/bin/env python3
"""Generate tokens.css (Chrome, Safari) from tokens/<style>.json, the brand kit's three appearances.

Styles: nocturne (Nocturne, the default, dark), paper (Paper & Ink, light), chromatic (Chromatic, dark).
Each style is one complete look with its own light or dark palette, so there is no separate mode.
Role names are identical in every file, so components never know which style is active. iOS reads
the same files through ios/tools/make-style-tokens.py. Standard library only.

    python3 -I replica/design/build_tokens.py

CSS contract: <html data-style="paper|chromatic">; a missing data-style means nocturne.
"""
import json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
STYLES = ["nocturne", "paper", "chromatic"]   # first = default
T = {s: json.load(open(os.path.join(HERE, "tokens", f"{s}.json"))) for s in STYLES}


def style_vars(t):
    d = t["display"]
    out = [f"--font-{k}: {v};" for k, v in t["font"].items()]
    out += [f"--w-display: {d['weight']};", f"--track-display: {d['tracking']};", f"--stretch-display: {d['stretch']};"]
    out.append(f"--bw: {t['stroke']}px;")
    out += [f"--r-{k}: {v}px;" for k, v in t["radius"].items()]
    out += [f"--c-{k}: {v};" for k, v in t["color"].items()]
    out += [f"--shadow-{k}: {v};" for k, v in t["shadow"].items()]
    out.append(f"color-scheme: {t['mode']};")
    return out


def block(sel, lines, indent="  "):
    return f"{sel} {{\n" + "\n".join(indent + l for l in lines) + "\n}"


def css():
    base = T[STYLES[0]]
    shared = []
    for k, t in base["type"].items():
        fam = "var(--font-display)" if t.get("font") == "display" else "var(--font-sans)"
        wt = "var(--w-display)" if t.get("font") == "display" else t["weight"]
        shared.append(f"--t-{k}: {wt} {t['size']}px/{t['line']}px {fam};")
    shared += [f"--s-{i}: {v}px;" for i, v in enumerate(base["space"])]
    shared += [f"--m-{k}: {base['motion'][k]};" for k in ("fast", "base", "slow", "ease")]
    out = ["/* Generated by build_tokens.py from tokens/*.json. Do not edit by hand. */"]
    for i, s in enumerate(STYLES):
        root = ":root" if i == 0 else f':root[data-style="{s}"]'
        out.append(block(root, (shared if i == 0 else []) + style_vars(T[s])))
    out.append("@media (prefers-reduced-motion: reduce) { :root { --m-fast: 0ms; --m-base: 0ms; --m-slow: 0ms; } }")
    return "\n".join(out) + "\n"


def shadow_css(text):
    """The same tokens for a closed shadow root: :root[...] becomes :host([...])."""
    def host(m):
        chain = m.group(1)
        return f":host({chain})" if chain else ":host"
    return re.sub(r":root((?:\[[^\]]+\]|:not\(\[[^\]]+\]\))*)", host, text)


EXT = os.path.join(HERE, "..", "..", "keepsake", "src")
css_text = css()
open(os.path.join(HERE, "tokens.css"), "w").write(css_text)
# The extension's copies. tests/design-tokens.test.mjs fails if these drift from the token sources.
open(os.path.join(EXT, "shared", "tokens.css"), "w").write(css_text)
open(os.path.join(EXT, "content", "tokens-content.js"), "w").write(
    "// Generated by replica/design/build_tokens.py. Do not edit by hand.\n"
    "// Internet Binder design tokens for the in-page capture card (a closed shadow root): the host element\n"
    "// carries data-style, exactly like <html> in the extension's own pages.\n"
    "globalThis.__keepsakeTokenCss = " + json.dumps(shadow_css(css_text)) + ";\n")
print("wrote tokens.css and the extension copies for", ", ".join(STYLES))
