// Produces Sealer test vectors with WebCrypto (the API the Chrome extension will use), so the iOS
// Sealer (CryptoKit) and Chrome are checked against the same bytes.
//   node ios/tools/sealer-vectors.mjs > ios/KeepsakeKit/Tests/KeepsakeKitTests/Fixtures/sealer-vectors.json

import { createPrivateKey, createPublicKey } from 'node:crypto';

const { subtle } = globalThis.crypto;
const hex = (b) => Buffer.from(b).toString('hex');
const fromHex = (h) => new Uint8Array(Buffer.from(h, 'hex'));
const b64url = (b) => Buffer.from(b).toString('base64url');
const PKCS8_X25519 = '302e020100300506032b656e04220420';

async function keys(privHex) {
  const der = Buffer.from(PKCS8_X25519 + privHex, 'hex');
  const pub = createPublicKey(createPrivateKey({ key: der, format: 'der', type: 'pkcs8' })).export({ format: 'jwk' }).x;
  const priv = await subtle.importKey('pkcs8', der, { name: 'X25519' }, false, ['deriveBits']);
  const pubKey = await subtle.importKey('raw', Buffer.from(pub, 'base64url'), { name: 'X25519' }, true, []);
  return { priv, pubKey, pubRaw: Buffer.from(pub, 'base64url') };
}

async function vector({ name, chromePriv, phonePriv, mailbox, nonce, recordName, plaintext }) {
  const chrome = await keys(chromePriv);
  const phone = await keys(phonePriv);
  const secret = await subtle.deriveBits({ name: 'X25519', public: chrome.pubKey }, phone.priv, 256);
  const ikm = await subtle.importKey('raw', secret, 'HKDF', false, ['deriveBits']);
  const keyBits = await subtle.deriveBits({ name: 'HKDF', hash: 'SHA-256', salt: fromHex(mailbox), info: new TextEncoder().encode('keepsake-pair-v1') }, ikm, 256);
  const key = await subtle.importKey('raw', keyBits, 'AES-GCM', false, ['encrypt']);
  const ct = await subtle.encrypt({ name: 'AES-GCM', iv: fromHex(nonce), additionalData: new TextEncoder().encode(recordName) }, key, new TextEncoder().encode(plaintext));
  return {
    name, chromePrivate: chromePriv, phonePrivate: phonePriv,
    chromePublic: hex(chrome.pubRaw), phonePublic: hex(phone.pubRaw),
    mailboxId: mailbox, pairingCode: `keepsake-pair:v1:${b64url(fromHex(mailbox))}:${b64url(chrome.pubRaw)}`,
    sharedSecret: hex(secret), key: hex(keyBits),
    nonce, recordName, plaintext, sealed: nonce + hex(ct),
  };
}

