// Bundles keepsake/src/shared/*.js into one classic script for JavaScriptCore (iOS).
// The shared rules are plain ES modules with named imports and exports only, so a small
// transform is enough: each module becomes a function whose locals stay private, and
// `globalThis.KeepsakeCore` holds every module's exports by name ("storage", "kinds", …).
//
//   node ios/tools/bundle-core.mjs [out]   (default: ios/KeepsakeKit/Sources/KeepsakeKit/Resources/keepsake-core.js)

import { readFileSync, writeFileSync, readdirSync, mkdirSync } from 'node:fs';
import { dirname, join, basename } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const shared = join(root, 'keepsake', 'src', 'shared');
const out = process.argv[2] || join(root, 'ios', 'KeepsakeKit', 'Sources', 'KeepsakeKit', 'Resources', 'keepsake-core.js');

// Imports name a module by its file name: './util.js' and '../instagram/post.js' become "util" and "post".
const IMPORT = /^import\s*\{([^}]*)\}\s*from\s*'\.{1,2}\/(?:[\w-]+\/)*([\w-]+)\.js';?\s*$/gm;
const REEXPORT = /^export\s*\{([^}]*)\}\s*from\s*'\.{1,2}\/(?:[\w-]+\/)*([\w-]+)\.js';?\s*$/gm;
// Modules outside src/shared that the shared rules import (pure, no browser APIs).
const EXTRA = [join('keepsake', 'src', 'instagram', 'post.js'), join('keepsake', 'src', 'ai', 'provider.js')];
const EXPORT_LIST = /^export\s*\{([^}]*)\};?\s*$/gm;
const EXPORT_DECL = /^export\s+(async\s+function\*?|function\*?|const|let|var|class)\s+([A-Za-z_$][\w$]*)/gm;

const names = (list) => list.split(',').map((s) => s.trim()).filter(Boolean).map((s) => {
  const [a, b] = s.split(/\s+as\s+/);
  return [a.trim(), (b || a).trim()];
});

export function transform(name, src) {
  const deps = new Set();
  const exports = [];
  let body = src.replace(IMPORT, (_, list, dep) => {
    deps.add(dep);
    return `const { ${names(list).map(([a, b]) => (a === b ? a : `${a}: ${b}`)).join(', ')} } = __m[${JSON.stringify(dep)}];`;
  });
  body = body.replace(REEXPORT, (_, list, dep) => {
    deps.add(dep);
    for (const [a, b] of names(list)) exports.push([b, `__m[${JSON.stringify(dep)}].${a}`]);
    return '';
  });
  body = body.replace(EXPORT_LIST, (_, list) => {
    for (const [a, b] of names(list)) exports.push([b, a]);
    return '';
  });
  body = body.replace(EXPORT_DECL, (_, kw, id) => {
    exports.push([id, id]);
    return `${kw} ${id}`;
  });
  if (/^\s*(import|export)\b/m.test(body)) throw new Error(`${name}: unsupported import/export form`);
  const getters = exports.map(([k, v]) => `get ${k}() { return ${v}; }`).join(', ');
  return { name, deps: [...deps], code: `__m[${JSON.stringify(name)}] = (function () {\n${body}\nreturn { ${getters} };\n})();\n` };
}

export function bundle() {
  const files = [...readdirSync(shared).filter((f) => f.endsWith('.js')).sort().map((f) => join(shared, f)), ...EXTRA.map((f) => join(root, f))];
  const mods = {};
  for (const file of files) {
    const name = basename(file, '.js');
    if (mods[name]) throw new Error(`two modules named ${name}`);
    mods[name] = transform(name, readFileSync(file, 'utf8'));
  }
  const order = [];
  const seen = new Set();
  const visit = (n, stack = []) => {
    if (seen.has(n)) return;
    if (stack.includes(n)) throw new Error(`import cycle: ${[...stack, n].join(' → ')}`);
    for (const d of mods[n].deps) visit(d, [...stack, n]);
    seen.add(n);
    order.push(n);
  };
  Object.keys(mods).forEach((n) => visit(n));
  const polyfills = readFileSync(join(here, 'jsc-polyfills.js'), 'utf8');
  const source = order.map((n) => mods[n].code).join('\n');
  const hash = createHash('sha256').update(source).digest('hex').slice(0, 12);
  return `// GENERATED by ios/tools/bundle-core.mjs from keepsake/src/shared. Do not edit. source ${hash}\n${polyfills}\nglobalThis.KeepsakeCore = (function () {\nconst __m = {};\n${source}\nreturn __m;\n})();\n`;
}

// Safari's JavaScript preprocessing file for the Share Extension: Chrome's own page reader
// (keepsake/src/extract/extract.js) run on the live page, its result handed to the extension as JSON.
export const shareExtractPath = join(root, 'ios', 'ShareExtension', 'ShareExtract.js');
export function shareExtract() {
  const extract = readFileSync(join(root, 'keepsake', 'src', 'extract', 'extract.js'), 'utf8');
  return `// GENERATED by ios/tools/bundle-core.mjs from keepsake/src/extract/extract.js. Do not edit.
// Safari runs this in the page when you share it to Keepsake (NSExtensionJavaScriptPreprocessingFile).
var ExtensionPreprocessingJS = {
  run: function (args) {
    var product = null;
    try {
${extract.split('\n').map((l) => (l ? '      ' + l : l)).join('\n')}
      product = globalThis.__keepsakeExtract ? globalThis.__keepsakeExtract() : null;
    } catch (e) { product = null; }
    args.completionFunction({ product: product ? JSON.stringify(product) : '', url: location.href, title: document.title });
  },
  finalize: function () {},
};
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, bundle());
  console.log(`wrote ${out}`);
  writeFileSync(shareExtractPath, shareExtract());
  console.log(`wrote ${shareExtractPath}`);
}
