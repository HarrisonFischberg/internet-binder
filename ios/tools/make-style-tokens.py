#!/usr/bin/env python3
"""Writes ios/KeepsakeKit/Sources/KeepsakeUI/StyleTokens.swift from replica/design/tokens/<style>.<mode>.json,
so iPhone, iPad and the Chrome extension draw every style with the same hex values.
Run: python3 ios/tools/make-style-tokens.py
"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
TOKENS = os.path.join(HERE, '..', '..', 'replica', 'design', 'tokens')
OUT = os.path.join(HERE, '..', 'KeepsakeKit', 'Sources', 'KeepsakeUI', 'StyleTokens.swift')
STYLES = ['pantry', 'notebook', 'gallery', 'atlas', 'swiss']

def colors(style, mode):
    with open(os.path.join(TOKENS, f'{style}.{mode}.json')) as f:
        data = json.load(f)
    out = {}
    def walk(o, path):
        for k, v in o.items():
            if isinstance(v, dict) and not any(x in v for x in ('value', '$value')):
                walk(v, path + [k])
            else:
                val = v.get('value', v.get('$value')) if isinstance(v, dict) else v
                if path[:1] == ['color'] and isinstance(val, str) and val.startswith('#') and len(val) == 7:
                    out['.'.join(path[1:] + [k])] = val[1:].upper()
    walk(data, [])
    return out

lines = ['// Generated by ios/tools/make-style-tokens.py from replica/design/tokens. Do not edit by hand.',
         '#if canImport(UIKit)', '',
         '/// Each style\'s colour tokens as (light, dark) hex, shared with the Chrome extension.',
         'enum StyleTokens {', '    static let values: [String: [String: (UInt32, UInt32)]] = [']
for s in STYLES:
    light, dark = colors(s, 'light'), colors(s, 'dark')
    lines.append(f'        "{s}": [')
    for key in sorted(set(light) & set(dark)):
        lines.append(f'            "{key}": (0x{light[key]}, 0x{dark[key]}),')
    lines.append('        ],')
lines += ['    ]', '}', '#endif', '']
with open(OUT, 'w') as f:
    f.write('\n'.join(lines))
print('wrote', os.path.relpath(OUT))
