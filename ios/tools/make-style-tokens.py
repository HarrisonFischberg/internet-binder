#!/usr/bin/env python3
"""Writes ios/KeepsakeKit/Sources/KeepsakeUI/StyleTokens.swift from replica/design/tokens/<style>.json,
so iPhone, iPad and the browser extensions draw every appearance with the same hex values.
Run: python3 ios/tools/make-style-tokens.py
"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
TOKENS = os.path.join(HERE, '..', '..', 'replica', 'design', 'tokens')
OUT = os.path.join(HERE, '..', 'KeepsakeKit', 'Sources', 'KeepsakeUI', 'StyleTokens.swift')
STYLES = ['nocturne', 'paper', 'chromatic']

lines = ['// Generated by ios/tools/make-style-tokens.py from replica/design/tokens. Do not edit by hand.',
         '#if canImport(UIKit)', '',
         '/// Each appearance\'s colour tokens as hex, shared with the browser extensions.',
         'enum StyleTokens {', '    static let values: [String: [String: UInt32]] = [']
for s in STYLES:
    with open(os.path.join(TOKENS, f'{s}.json')) as f:
        colors = json.load(f)['color']
    lines.append(f'        "{s}": [')
    for key in sorted(colors):
        lines.append(f'            "{key}": 0x{colors[key][1:].upper()},')
    lines.append('        ],')
lines += ['    ]', '}', '#endif', '']
with open(OUT, 'w') as f:
    f.write('\n'.join(lines))
print('wrote', os.path.relpath(OUT))
